import type { ApprovalDto } from "@homeflow/shared";
import { Check, ClipboardList, Loader2, ShoppingBasket, X } from "lucide-react";
import { formatDue, formatQuantity } from "../../lib/format";

const STATUS_COPY: Record<ApprovalDto["status"], string> = {
  PENDING: "Awaiting your approval",
  APPROVED: "Approved, executing…",
  REJECTED: "Rejected. Nothing was changed.",
  EXPIRED: "Expired. Ask for a new plan.",
  EXECUTED: "Executed and saved",
  FAILED: "Some actions failed",
};

export function PlanPreview({
  approval,
  busy,
  onApprove,
  onReject,
}: {
  approval: ApprovalDto;
  busy: "idle" | "planning" | "approving" | "rejecting";
  onApprove: () => void;
  onReject: () => void;
}) {
  const pending = approval.status === "PENDING";
  return (
    <section aria-label="Proposed actions" className="rounded-xl border border-teal-200 bg-teal-50/60 p-4">
      <div className="flex items-start justify-between gap-2">
        <div>
          <h3 className="text-sm font-semibold">Proposed plan</h3>
          <p className="mt-0.5 text-xs text-slate-600">{approval.summary}</p>
        </div>
        <span
          className={`shrink-0 rounded-full px-2 py-0.5 text-xs font-medium ${approval.status === "EXECUTED" ? "bg-teal-600 text-white" : approval.status === "FAILED" || approval.status === "EXPIRED" ? "bg-red-100 text-red-800" : "bg-white text-navy-900 ring-1 ring-slate-200"}`}
        >
          {STATUS_COPY[approval.status]}
        </span>
      </div>

      <ul className="mt-3 max-h-64 space-y-1.5 overflow-y-auto pr-1">
        {approval.actions.map((a, i) => {
          const result = approval.results?.find((r) => r.index === i);
          return (
            <li key={i} className="flex items-start gap-2 rounded-lg bg-white px-3 py-2 text-sm shadow-sm">
              {a.type === "create_task" ? (
                <ClipboardList className="mt-0.5 size-4 shrink-0 text-navy-700" aria-label="Task" />
              ) : (
                <ShoppingBasket className="mt-0.5 size-4 shrink-0 text-teal-600" aria-label="Grocery item" />
              )}
              <div className="min-w-0 flex-1">
                <p className="font-medium">{a.type === "create_task" ? a.title : a.name}</p>
                <p className="text-xs text-slate-500">
                  {a.type === "create_task" ? formatDue(a.dueDate ?? null) : formatQuantity(a.quantity ?? 1, a.unit ?? null)}
                </p>
              </div>
              {result &&
                (result.ok ? (
                  <Check className="size-4 text-teal-600" aria-label="Completed" />
                ) : (
                  <span className="text-xs text-red-700" role="alert">
                    {result.message}
                  </span>
                ))}
            </li>
          );
        })}
      </ul>

      {pending && (
        <div className="mt-3 flex gap-2">
          <button
            onClick={onApprove}
            disabled={busy !== "idle"}
            className="inline-flex items-center gap-1.5 rounded-lg bg-teal-600 px-3.5 py-2 text-sm font-semibold text-white hover:bg-teal-700 disabled:cursor-not-allowed disabled:opacity-60"
          >
            {busy === "approving" ? <Loader2 className="size-4 animate-spin" aria-hidden /> : <Check className="size-4" aria-hidden />}
            {busy === "approving" ? "Waiting for backend…" : `Approve ${approval.actions.length} actions`}
          </button>
          <button
            onClick={onReject}
            disabled={busy !== "idle"}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-300 bg-white px-3.5 py-2 text-sm font-medium hover:bg-slate-50 disabled:cursor-not-allowed disabled:opacity-60"
          >
            <X className="size-4" aria-hidden /> Reject
          </button>
        </div>
      )}
      {approval.isMock && (
        <p className="mt-2 text-xs text-amber-700">Generated by the deterministic mock provider (demo mode), not a real AI model.</p>
      )}
    </section>
  );
}
